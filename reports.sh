#!/usr/bin/env bash

###############################################################################
# HPCForge reporting helpers
###############################################################################

summary() {
    local title="$1"
    shift

    echo
    echo "============================================================"
    echo " $title"
    echo "============================================================"

    while [[ $# -gt 1 ]]; do
        printf "  %-16s : %s\n" "$1" "$2"
        shift 2
    done

    echo "============================================================"
    echo
}